            FormatBadge(name = "Excel", color = Color(0xFF1E7E34))
            FormatBadge(name = "Word", color = Color(0xFF185ABD))
            FormatBadge(name = "PDF", color = Color(0xFFD32F2F))
            FormatBadge(name = "TXT/CSV", color = Color(0xFFE65100))
        }

        Spacer(modifier = Modifier.height(16.dp))

        Text(
            text = "يدعم البحث الفوري بجميع صيغ الحروف العربية (أ/إ/آ، ة/ه، ى/ي) ومع أو بدون التشكيل.",
            style = MaterialTheme.typography.bodySmall,
            color = MaterialTheme.colorScheme.outline,
            textAlign = TextAlign.Center
